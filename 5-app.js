function updateLyricStage(currentTime) {
  if (!expanded || lyricView !== 'dynamic') return;
  const lines = getCurrentLyrics();
  const { lineIndex, wordIndex } = getActiveLyricPosition(currentTime);
  const nextIndex = lineIndex >= 0 ? lineIndex + 1 : lines.findIndex(line => line.start > currentTime);
  const key = `${currentIndex}:${lineIndex}:${nextIndex}`;
  if (key !== stageKey) {
    stageKey = key;
    lyricStage.replaceChildren();
    if (lineIndex >= 0) {
      const current = lyrics.children[lineIndex].cloneNode(true);
      current.classList.add('stage-current');
      current.classList.add('is-active');
      current.setAttribute('aria-current', 'true');
      lyricStage.append(current);
    } else {
      const message = document.createElement('p');
      message.className = 'stage-message';
      message.textContent = nextIndex >= 0 ? (currentTime < lines[0].start ? '準備一起唱' : '間奏') : '演唱結束';
      lyricStage.append(message);
    }
    if (nextIndex >= 0 && nextIndex < lines.length) {
      const next = lyrics.children[nextIndex].cloneNode(true);
      next.className = 'lyric-line stage-next';
      next.removeAttribute('aria-current');
      next.querySelector('.line-label').textContent = '下一句';
      next.querySelectorAll('.is-word-active').forEach(word => word.classList.remove('is-word-active'));
      lyricStage.append(next);
    }
    lyricStage.scrollTop = 0;
  }
  lyricStage.querySelectorAll('.stage-current .lyric-word').forEach((word, index) => {
    word.classList.toggle('is-word-active', lyricMotion === 'word' && index === wordIndex);
  });
}

function getLyricWindow(line) {
  return { start: line.start, end: line.end };
}

function getActiveLyricIndex(currentTime) {
  return getCurrentLyrics().findIndex((line) => {
    const { start, end } = getLyricWindow(line);
    return Number.isFinite(start) && Number.isFinite(end) && currentTime >= start && currentTime < end;
  });
}

function isTimedWord(word) {
  return word.text.trim() && !/[，。！？、；：,.!?;:]/u.test(word.text);
}

function getWordWindow(line, wordIndex) {
  const word = line.words[wordIndex];
  if (!word || !isTimedWord(word)) return null;
  if (Number.isFinite(word.start) && Number.isFinite(word.end) && word.end > word.start) {
    return { start: word.start, end: word.end };
  }
  return null;
}

function getActiveLyricPosition(currentTime) {
  const lineIndex = getActiveLyricIndex(currentTime);
  if (lineIndex < 0) return { lineIndex: -1, wordIndex: -1 };
  const line = getCurrentLyrics()[lineIndex];
  const wordIndex = line.words.findIndex((word, index) => {
    const window = getWordWindow(line, index);
    return window && currentTime >= window.start && currentTime < window.end;
  });
  return { lineIndex, wordIndex };
}

function updateLyrics(currentTime, { scroll = true } = {}) {
  updateLyricStage(currentTime);
  const { lineIndex: nextIndex, wordIndex: nextWordIndex } = getActiveLyricPosition(currentTime);
  const lineChanged = nextIndex !== activeLyricIndex;
  const lineElements = lyrics.querySelectorAll('.lyric-line');
  lineElements.forEach((element, index) => {
    const isActive = index === nextIndex;
    element.classList.toggle('is-active', isActive);
    element.setAttribute('aria-current', isActive ? 'true' : 'false');
    element.querySelectorAll('.lyric-word').forEach((wordElement, wordIndex) => {
      wordElement.classList.toggle('is-word-active', lyricMotion === 'word' && isActive && wordIndex === nextWordIndex);
    });
  });

  if (nextIndex < 0 || nextIndex !== activeLyricIndex || nextWordIndex !== activeLyricWordIndex) {
    activeLyricIndex = nextIndex;
    activeLyricWordIndex = nextWordIndex;
    if (nextIndex >= 0) {
      const line = getCurrentLyrics()[nextIndex];
      const words = line.words.map(word => word.text).join('').trim();
      const activeWord = lyricMotion === 'word' ? line.words[nextWordIndex]?.text : null;
      lyricLiveStatus.textContent = activeWord ? `目前句：${words}・唱到「${activeWord}」` : `目前句：${words}`;
      if (lineChanged && scroll && !audio.paused && lyricView === 'dynamic' && !expanded) {
        lineElements[nextIndex]?.scrollIntoView({ behavior: 'smooth', block: 'center' });
      }
    } else {
      const hasTimedLine = getCurrentLyrics().some((line) => Number.isFinite(line.start) && Number.isFinite(line.end));
      const nextLine = getCurrentLyrics().find(line => Number.isFinite(line.start) && line.start > currentTime);
      lyricLiveStatus.textContent = getCurrentSong().timingStatus === 'auto-candidate' && nextLine
        ? `前奏／間奏中，下一句約 ${Math.max(0, Math.ceil(nextLine.start - currentTime))} 秒後開始`
        : getCurrentSong().timingStatus === 'auto-candidate' && hasTimedLine
          ? '目前在自動逐字對齊候選的間奏區間'
        : hasTimedLine
          ? '目前時間尚未進入已校時歌詞區間'
          : '正式時間軸待校對，暫不顯示逐字高亮';
    }
  }
}

function updateTrackDetails() {
  const song = getCurrentSong();
  document.querySelector('#track-title').textContent = song.title;
  document.querySelector('#track-subtitle').textContent = song.description;
  const verifiedLines = getCurrentLyrics().filter((line) => Number.isFinite(line.start) && Number.isFinite(line.end)).length;
  if (song.timingStatus === 'verified' && verifiedLines === getCurrentLyrics().length && verifiedLines > 0) {
    lyricsStatusChip.textContent = '完整歌詞・正式時間軸';
    lyricsStatusChip.classList.remove('pending');
    lyricsNoticeText.textContent = '歌詞會依正式時間軸逐字高亮，並在換句時自動捲動。';
  } else if (song.timingStatus === 'auto-candidate' && verifiedLines === getCurrentLyrics().length && verifiedLines > 0) {
    lyricsStatusChip.textContent = '完整歌詞・自動逐字對齊候選';
    lyricsStatusChip.classList.add('pending');
    lyricsNoticeText.textContent = '已用大型語音模型產生逐字時間，可先跟唱預覽；低信心字仍待播放抽查，不等於正式人工校時。';
  } else {
    lyricsStatusChip.textContent = `完整歌詞・${verifiedLines}/${getCurrentLyrics().length} 句已校時`;
    lyricsStatusChip.classList.add('pending');
    lyricsNoticeText.textContent = '兩首完整歌詞與逐字注音已載入；正式時間軸仍需逐句聽讀校對，未校對處不會顯示假同步。';
  }
  renderPlaylist();
  renderLyrics();
}

