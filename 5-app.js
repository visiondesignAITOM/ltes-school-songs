function loadSong(index, autoplay = false) {
  currentIndex = (index + songs.length) % songs.length;
  audio.src = encodeURI(getCurrentSong().audio);
  audio.load();
  progress.value = '0';
  progress.max = '0';
  document.querySelector('#current-time').textContent = '0:00';
  document.querySelector('#duration').textContent = getCurrentSong().durationLabel;
  updateTrackDetails();
  activeLyricIndex = -1;
  activeLyricWordIndex = -1;
  lyricLiveStatus.textContent = getCurrentSong().timingStatus === 'verified'
    ? '尚未播放'
    : getCurrentSong().timingStatus === 'auto-candidate'
      ? '自動逐字對齊候選已載入，播放後會逐字高亮'
      : '正式時間軸待校對';
  setStatus(`已選取 ${getCurrentSong().title}`);
  if (autoplay) {
    audio.play().catch(() => setStatus('瀏覽器需要先點擊播放才能開始音訊'));
  }
}

