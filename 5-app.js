function renderLyricLines(container, lines) {
  activeLyricIndex = -1;
  activeLyricWordIndex = -1;
  container.replaceChildren();
  lines.forEach((line, lineIndex) => {
    const lineElement = document.createElement('div');
    lineElement.className = 'lyric-line';
    lineElement.dataset.lineIndex = lineIndex;
    const timedLine = container === staticLyrics
      ? getCurrentLyrics().find((entry, index) => (entry.sourceLineIndex ?? index) === lineIndex)
      : line;
    if (Number.isFinite(timedLine?.start)) {
      lineElement.dataset.seekTime = timedLine.start;
      lineElement.tabIndex = 0;
      lineElement.setAttribute('role', 'button');
      lineElement.setAttribute('aria-label', `播放這句：${line.words.map(word => word.text).join('')}`);
    }
    lineElement.innerHTML = `<span class="line-label">${line.label}</span><span class="lyric-words"></span>`;
    const words = lineElement.querySelector('.lyric-words');
    line.words.forEach((word, wordIndex) => {
      const wordElement = document.createElement('span');
      wordElement.className = 'lyric-word';
      wordElement.dataset.wordIndex = wordIndex;
      wordElement.dataset.text = word.text;
      wordElement.innerHTML = `<span class="zhuyin">${word.zhuyin}</span><span class="hanzi">${word.text}</span>`;
      const reading = effectiveReading(word);
      const readingKey = `${word.text}|${reading}`;
      wordElement.querySelector('.zhuyin').textContent = reading;
      if (reading && window.bpmfFontFailed !== true && Object.hasOwn(window.BPMF_VARIANTS || {}, readingKey)) {
        wordElement.classList.add('has-bpmf-font');
        wordElement.querySelector('.hanzi').textContent = word.text + window.BPMF_VARIANTS[readingKey];
        wordElement.setAttribute('aria-label', `${word.text} ${reading}`);
      }
      words.append(wordElement);
      wordElement.addEventListener('click', event => {
        if (!pronunciationCalibrationMode) return;
        event.stopPropagation();
        pronunciationTarget = { word };
        document.querySelector('#pronunciation-character').textContent = word.text;
        pronunciationInput.value = reading;
        pronunciationDialog.showModal();
        pronunciationInput.focus();
        pronunciationInput.select();
      });
    });
    // All source lyrics have reviewed phrase boundaries. Original word nodes
    // and timing indices remain intact, including whitespace and punctuation.
    const phraseText = line.words.map(word => word.text).join('').replace(/\s/gu, '');
    const phrases = LYRIC_PHRASES[phraseText];
    if (!phrases) throw new Error(`缺少歌詞斷句：${phraseText}`);
    const tokens = [...words.children];
    let offset = 0;
    phrases.forEach(text => {
      const phrase = document.createElement('span');
      phrase.className = 'lyric-phrase';
      let content = '';
      while (offset < tokens.length && content.length < text.length) {
        const token = tokens[offset++];
        content += token.dataset.text.replace(/\s/gu, '');
        phrase.append(token);
      }
      while (offset < tokens.length && !tokens[offset].dataset.text.trim()) phrase.append(tokens[offset++]);
      if (content !== text) throw new Error(`歌詞斷句不一致：${text}`);
      words.append(phrase);
    });
    const widest = Math.max(...phrases.map(text => [...text].reduce((width, char) => width + (/[A-Za-z]/u.test(char) ? 1 : /[，。！？、；：]/u.test(char) ? 1.2 : 1.9), 0)));
    lineElement.style.setProperty('--phrase-width', widest + .8);
    container.append(lineElement);
  });
}

function seekToLyric(element) {
  const time = Number(element.dataset.seekTime);
  if (!Number.isFinite(time)) return;
  const songIndex = currentIndex;
  const seek = () => {
    if (currentIndex !== songIndex) return;
    audio.currentTime = Math.min(time, Number.isFinite(audio.duration) ? audio.duration : time);
    progress.value = String(audio.currentTime);
    document.querySelector('#current-time').textContent = formatTime(audio.currentTime);
    updateLyrics(audio.currentTime, { scroll: false });
  };
  if (audio.readyState > 0) seek();
  else audio.addEventListener('loadedmetadata', seek, { once: true });
  audio.play().catch(() => setStatus('已跳到這句，請按播放開始'));
}
[lyrics, staticLyrics, lyricStage].forEach(container => {
  container.addEventListener('click', event => {
    const line = event.target.closest('[data-seek-time]');
    if (line && container.contains(line)) seekToLyric(line);
  });
  container.addEventListener('keydown', event => {
    if (event.key !== 'Enter' && event.key !== ' ') return;
    const line = event.target.closest('[data-seek-time]');
    if (!line) return;
    event.preventDefault();
    seekToLyric(line);
  });
});

