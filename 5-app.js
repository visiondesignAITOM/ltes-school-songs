function syncPlaybackUI() {
  progress.value = String(audio.currentTime);
  document.querySelector('#current-time').textContent = formatTime(audio.currentTime);
  updateLyrics(audio.currentTime);
  if (!audio.paused && !audio.ended) playbackFrame = requestAnimationFrame(syncPlaybackUI);
}

function startPlaybackSync() {
  if (playbackFrame !== null) cancelAnimationFrame(playbackFrame);
  playbackFrame = requestAnimationFrame(syncPlaybackUI);
}

function stopPlaybackSync() {
  if (playbackFrame !== null) cancelAnimationFrame(playbackFrame);
  playbackFrame = null;
  syncPlaybackUI();
}

function togglePlayback() {
  if (audio.paused) {
    audio.play().catch(() => setStatus('瀏覽器需要先點擊播放才能開始音訊'));
  } else {
    audio.pause();
  }
}

function seekBy(seconds) {
  if (!Number.isFinite(audio.duration)) return;
  audio.currentTime = Math.min(audio.duration, Math.max(0, audio.currentTime + seconds));
  setStatus(`${seconds > 0 ? '前進' : '後退'} ${Math.abs(seconds)} 秒`);
}

function setLoopMode(mode) {
  loopMode = mode;
  const labels = { none: '不重複', one: '重複這首', all: '全部重複' };
  const helps = { none: '播放結束後停止', one: '目前歌曲結束後重新播放', all: '歌單結束後回到第一首' };
  loopOptions.forEach((option) => {
    const isSelected = option.dataset.loopMode === loopMode;
    option.classList.toggle('is-selected', isSelected);
    option.setAttribute('aria-checked', String(isSelected));
  });
  loopHelp.textContent = helps[loopMode];
  setStatus(`循環模式：${labels[loopMode]}`);
}

