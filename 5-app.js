const songs = window.ltesSongs;

function applyTimingCandidates() {
  const candidates = window.ltesTimingCandidates || {};
  songs.forEach((song) => {
    const candidate = candidates[song.id];
    if (!candidate) return;
    const candidateLines = candidate.timeline || candidate.lines;
    if (!Array.isArray(candidateLines)) throw new Error(`${song.id} 缺少自動時間候選`);
    if (!candidate.timeline && candidateLines.length !== song.lyrics.length) throw new Error(`${song.id} 自動時間候選句數不一致`);

    const occurrenceCounts = candidateLines.reduce((counts, line, index) => {
      const sourceLineIndex = line.sourceLineIndex ?? index;
      counts[sourceLineIndex] = (counts[sourceLineIndex] || 0) + 1;
      return counts;
    }, {});
    song.playbackLyrics = candidateLines.map((candidateLine, timelineIndex) => {
      const sourceLineIndex = candidateLine.sourceLineIndex ?? timelineIndex;
      const sourceLine = song.lyrics[sourceLineIndex];
      if (!sourceLine) throw new Error(`${song.id} 第 ${timelineIndex + 1} 段來源句不存在`);
      if (!Array.isArray(candidateLine.words) || candidateLine.words.length !== sourceLine.words.length) {
        throw new Error(`${song.id} 第 ${timelineIndex + 1} 段候選 token 數不一致`);
      }
      const occurrence = candidateLine.occurrence || 1;
      return {
        ...sourceLine,
        sourceLineIndex,
        occurrence,
        label: occurrenceCounts[sourceLineIndex] > 1 ? `${sourceLine.label} · ${occurrence}/${occurrenceCounts[sourceLineIndex]}` : sourceLine.label,
        start: candidateLine.start,
        end: candidateLine.end,
        words: sourceLine.words.map((word, wordIndex) => {
          const candidateWord = candidateLine.words[wordIndex];
          if (word.text !== candidateWord.text) {
            throw new Error(`${song.id} 第 ${timelineIndex + 1} 段候選文字不一致`);
          }
          return { ...word, start: candidateWord.start, end: candidateWord.end, timingConfidence: candidateWord.confidence };
        }),
      };
    });
    song.timingStatus = candidate.status;
    song.timingModel = candidate.model;
  });
}

applyTimingCandidates();

